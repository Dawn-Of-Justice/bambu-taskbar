// This allows TypeScript to pick up the magic constants that's auto-generated by Forge's Webpack
// plugin that tells the Electron app where to look for the Webpack-bundled app code (depending on
// whether you're running in development or production).
declare const MAIN_WINDOW_WEBPACK_ENTRY: string;
declare const MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY: string;

const GITHUB_URL = 'https://github.com/Dawn-Of-Justice/bambu-taskbar';
const SETUP_GUIDE_URL = `${GITHUB_URL}#local-network-mode-optional`;

// Handle creating/removing shortcuts on Windows when installing/uninstalling.
// eslint-disable-next-line @typescript-eslint/no-var-requires
const isSquirrelEvent: boolean = require('electron-squirrel-startup');
// Only one tray icon: a second launch just opens the settings of the running instance.
const shouldExit = isSquirrelEvent || !app.requestSingleInstanceLock();
if (shouldExit) {
  app.quit();
}

// Squirrel's Start menu shortcut uses this AppUserModelID; notifications need it to match.
app.setAppUserModelId(app.isPackaged ? 'com.squirrel.bambu_taskbar.bambu-taskbar' : process.execPath);

const iconRenderer = new IconRenderer();
const notifier = new PrintNotifier();
let settingsWindow: BrowserWindow | null = null;
let trayManager: TrayManager | null = null;
let stopThemeWatch: (() => void) | null = null;
let lightTaskbar = false;
let client: BambuClient | null = null;
let status: PrintStatus = emptyStatus('unconfigured', null);
let cloudHttp: ElectronHttpClient | null = null;
let cloudLogin: CloudLogin | null = null;
let expiryWarned = false;

function emptyStatus(connection: PrintStatus['connection'], message: string | null): PrintStatus {
  const s = getSettings();
  return {
    connection, connectionMessage: message, mode: s.connectionMode,
    printerName: s.printerName || s.printerSerial || 'Printer', model: s.printerModel || null,
    state: 'unknown', percent: null, remainingMinutes: null, layer: null, totalLayers: null, fileName: null,
    stageName: null, nozzleTemp: null, nozzleTarget: null, bedTemp: null, bedTarget: null, errorCode: null,
    lastUpdate: null,
  };
}

// ---------- Printer ----------

function setStatus(next: PrintStatus): void {
  status = next;
  trayManager?.setStatus(next);
  notifier.onStatus(next, getSettings());
  if (settingsWindow && !settingsWindow.isDestroyed()) {
    settingsWindow.webContents.send('statusChanged', next);
  }
}

function startPrinter(): void {
  client?.stop();
  client = null;
  const s = getSettings();
  const common = {
    serial: s.printerSerial,
    name: s.printerName || s.printerSerial,
    model: s.printerModel || null,
  };

  if (s.connectionMode === 'cloud') {
    const token = decryptSecret(s.cloudTokenEncrypted);
    if (!token || !s.cloudUsername) {
      setStatus(emptyStatus('signed-out', 'Sign in with your Bambu Lab account below.'));
      return;
    }
    if (!s.printerSerial) {
      setStatus(emptyStatus('unconfigured', 'Choose which printer to show.'));
      return;
    }
    client = new BambuClient({ mode: 'cloud', host: mqttHost(s.cloudRegion), username: s.cloudUsername, password: token, ...common });
  } else {
    const accessCode = decryptSecret(s.accessCodeEncrypted);
    if (!s.printerHost || !s.printerSerial || !accessCode) {
      setStatus(emptyStatus('unconfigured', 'Enter the printer details above, then Save and connect.'));
      return;
    }
    client = new BambuClient({
      mode: 'lan',
      host: s.printerHost,
      username: 'bblp',
      password: accessCode,
      ca: fs.readFileSync(BAMBU_CA_PATH),
      verifyPrinterIdentity: true,
      allowUnverified: s.allowUnverifiedCertificate,
      ...common,
    });
  }
  client.on('status', next => {
    if (next.mode === 'cloud' && next.connection === 'auth-failed' && !expiryWarned) {
      expiryWarned = true;
      showNotification({ title: 'Sign in to Bambu Lab again', body: 'Your Bambu Lab sign-in has expired. Open Bambu Taskbar settings to sign in.' });
    }
    setStatus(next);
  });
  client.start();
}

// ---------- Bambu account ----------

function http(): ElectronHttpClient {
  if (!cloudHttp) { cloudHttp = new ElectronHttpClient(); }
  return cloudHttp;
}

async function storeCloudSession(session: CloudSession): Promise<CloudLoginStep> {
  await updateSettings({
    connectionMode: 'cloud',
    cloudRegion: session.region,
    cloudEmail: session.email,
    cloudUsername: session.username,
    cloudTokenEncrypted: encryptSecret(session.token),
    cloudTokenExpiresAt: session.expiresAt,
  });
  cloudLogin = null;
  expiryWarned = false;
  // Pick the printer automatically when the account has exactly one.
  if (!getSettings().printerSerial) {
    const printers = await cloudPrinters().catch((): CloudPrinter[] => []);
    if (printers.length === 1) { await selectCloudPrinter(printers[0]); return 'signed-in'; }
  }
  startPrinter();
  return 'signed-in';
}

async function cloudSignIn(email: string, password: string, region: CloudRegion): Promise<CloudLoginStep> {
  await http().reset();
  cloudLogin = new CloudLogin(http());
  const result = await cloudLogin.start(String(email ?? ''), String(password ?? ''), region === 'china' ? 'china' : 'global');
  return result.status === 'signed-in' ? storeCloudSession(result.session) : result.status;
}

/** Sign in on Bambu Lab's own website (Google, Apple or email), in a window. */
async function cloudSignInWithBrowser(region: CloudRegion): Promise<CloudLoginStep | 'cancelled'> {
  const r: CloudRegion = region === 'china' ? 'china' : 'global';
  cloudLogin = null;
  const result = await signInWithBrowser(r, settingsWindow);
  if (!result) { return 'cancelled'; }
  settingsWindow?.focus();
  return storeCloudSession(await sessionFromToken(http(), r, result.token, { expiresAt: result.expiresAt }));
}

async function cloudPrinters(): Promise<CloudPrinter[]> {
  const s = getSettings();
  const token = decryptSecret(s.cloudTokenEncrypted);
  if (!token) { throw new Error('Sign in with your Bambu Lab account first.'); }
  return listCloudPrinters(http(), { region: s.cloudRegion, token });
}

async function selectCloudPrinter(p: CloudPrinter): Promise<void> {
  if (!p || typeof p.serial !== 'string' || !/^[A-Za-z0-9]{8,24}$/.test(p.serial)) { throw new Error('Invalid printer.'); }
  await updateSettings({
    connectionMode: 'cloud',
    printerSerial: p.serial,
    printerName: String(p.name ?? ''),
    printerModel: String(p.model ?? ''),
  });
  startPrinter();
}

async function cloudSignOut(): Promise<void> {
  cloudLogin = null;
  await http().reset();
  await clearBrowserSignIn().catch(() => undefined);
  await updateSettings({ cloudEmail: '', cloudUsername: '', cloudTokenEncrypted: '', cloudTokenExpiresAt: 0 });
  startPrinter();
}

async function savePrinter(input: PrinterConnectionInput): Promise<void> {
  const host = String(input.host ?? '').trim();
  const serial = String(input.serial ?? '').trim().toUpperCase();
  const code = String(input.accessCode ?? '').trim();
  if (!/^[\w.-]+$/.test(host)) { throw new Error('Enter the printer\'s IP address, e.g. 192.168.1.42.'); }
  if (!/^[A-Z0-9]{8,20}$/.test(serial)) { throw new Error('Enter the printer\'s serial number (letters and digits).'); }
  if (code && !/^[A-Za-z0-9]{4,16}$/.test(code)) { throw new Error('The access code is the 8-character code shown on the printer.'); }
  if (!code && !getSettings().accessCodeEncrypted) { throw new Error('Enter the access code shown on the printer.'); }

  const changes: Partial<AppSettings> = {
    connectionMode: 'lan',
    printerName: String(input.name ?? '').trim(),
    printerHost: host,
    printerSerial: serial,
    printerModel: String(input.model ?? '').trim(),
  };
  if (code) { changes.accessCodeEncrypted = encryptSecret(code); }
  await updateSettings(changes);
  startPrinter();
}

// ---------- Settings window ----------

/** Mica needs Windows 11 22H2 (build 22621) or newer. */
function supportsMica(): boolean {
  if (process.platform !== 'win32') { return false; }
  const build = parseInt(os.release().split('.')[2] ?? '0');
  return build >= 22621;
}

function titleBarOverlay() {
  return {
    color: 'rgba(0,0,0,0)',
    symbolColor: nativeTheme.shouldUseDarkColors ? '#ffffff' : '#1b1b1b',
    height: 44,
  };
}

function openSettingsWindow(): void {
  if (settingsWindow && !settingsWindow.isDestroyed()) {
    if (settingsWindow.isMinimized()) { settingsWindow.restore(); }
    settingsWindow.show();
    settingsWindow.focus();
    return;
  }

  const mica = supportsMica();
  settingsWindow = new BrowserWindow({
    width: 800,
    height: 800,
    minWidth: 560,
    minHeight: 520,
    show: false,
    title: 'Bambu Taskbar',
    icon: APP_ICON_PATH,
    autoHideMenuBar: true,
    backgroundColor: mica ? '#00000000' : (nativeTheme.shouldUseDarkColors ? '#202020' : '#f3f3f3'),
    ...(mica ? { backgroundMaterial: 'mica' as const } : {}),
    titleBarStyle: 'hidden',
    titleBarOverlay: titleBarOverlay(),
    webPreferences: {
      preload: MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY,
      contextIsolation: true,
      sandbox: true,
    },
  });
  settingsWindow.removeMenu();
  settingsWindow.once('ready-to-show', () => settingsWindow?.show());
  settingsWindow.on('closed', () => { settingsWindow = null; });
  // Open links in the default browser, never inside the app.
  settingsWindow.webContents.setWindowOpenHandler(({ url }) => {
    if (url.startsWith('https://')) { void shell.openExternal(url); }
    return { action: 'deny' };
  });
  settingsWindow.webContents.on('will-navigate', e => e.preventDefault());
  void settingsWindow.loadURL(MAIN_WINDOW_WEBPACK_ENTRY);
}

function registerIpc(): void {
  ipcMain.handle('getSettings', () => getPublicSettings());
  ipcMain.handle('updateSettings', async (_, changes: Partial<PublicSettings>) => {
    const allowed: Partial<AppSettings> = {};
    for (const key of RENDERER_EDITABLE_KEYS) {
      if (changes && key in changes) { (allowed as Record<string, unknown>)[key] = (changes as Record<string, unknown>)[key]; }
    }
    await updateSettings(allowed);
  });
  ipcMain.handle('savePrinter', (_, input: PrinterConnectionInput) => savePrinter(input));
  ipcMain.handle('setConnectionMode', async (_, mode: ConnectionMode) => {
    await updateSettings({ connectionMode: mode === 'lan' ? 'lan' : 'cloud' });
    startPrinter();
  });
  ipcMain.handle('cloudSignIn', (_, email: string, password: string, region: CloudRegion) => cloudSignIn(email, password, region));
  ipcMain.handle('cloudSignInWithBrowser', (_, region: CloudRegion) => cloudSignInWithBrowser(region));
  ipcMain.handle('cloudVerifyCode', async (_, code: string) => {
    if (!cloudLogin) { throw new Error('Start signing in again.'); }
    return storeCloudSession(await cloudLogin.verifyCode(String(code ?? '')));
  });
  ipcMain.handle('cloudVerifyTfa', async (_, code: string) => {
    if (!cloudLogin) { throw new Error('Start signing in again.'); }
    return storeCloudSession(await cloudLogin.verifyTfa(String(code ?? '')));
  });
  ipcMain.handle('cloudResendCode', async () => {
    if (!cloudLogin) { throw new Error('Start signing in again.'); }
    await cloudLogin.sendCode();
  });
  ipcMain.handle('cloudSignOut', () => cloudSignOut());
  ipcMain.handle('cloudListPrinters', () => cloudPrinters());
  ipcMain.handle('cloudSelectPrinter', (_, p: CloudPrinter) => selectCloudPrinter(p));
  ipcMain.handle('getStatus', () => status);
  ipcMain.handle('discoverPrinters', (_, seconds: number) => discoverPrinters(Number(seconds) || 6));
  ipcMain.handle('getAppInfo', (): AppInfo => ({
    version: app.getVersion(),
    supportsMica: supportsMica(),
    lightTaskbar,
  }));
  ipcMain.handle('renderIcon', (_, r: IconPreviewRequest) => iconRenderer.renderDataUrl({
    style: r.style === 'ring' ? 'ring' : 'percent',
    state: r.state,
    percent: typeof r.percent === 'number' ? r.percent : null,
    lightTaskbar: !!r.lightTaskbar,
  }, Number(r.size) || 32));
  ipcMain.handle('sendTestNotification', () => {
    showNotification({ title: 'Bambu Taskbar', body: 'Notifications are working. You will be told when a print finishes or needs attention.' });
  });
  ipcMain.handle('openExternal', async (_, target: 'github' | 'setup-guide') => {
    await shell.openExternal(target === 'setup-guide' ? SETUP_GUIDE_URL : GITHUB_URL);
  });
}

// ---------- App lifecycle ----------

app.on('second-instance', () => openSettingsWindow());

// Keep running in the tray when the settings window closes.
app.on('window-all-closed', () => { /* do not quit */ });

app.on('ready', async () => {
  if (shouldExit) { return; }
  registerIpc();

  let isFirstTimeLaunch = false;
  settingsChanges.on('_defaultSettingsCreated', () => isFirstTimeLaunch = true);
  settingsChanges.on('runAtStartup', value => applyRunAtStartup(value));
  await loadSettings();

  iconRenderer.clearIconCache(); // drawing code may have changed since the last run
  await iconRenderer.init();
  trayManager = new TrayManager(iconRenderer, [
    { label: 'Settings…', click: () => openSettingsWindow() },
    { label: 'Reconnect', click: () => startPrinter() },
    { label: 'Quit', click: () => quit() },
  ], () => openSettingsWindow());
  await trayManager.init();

  settingsChanges.on('iconStyle', () => { void trayManager?.update(); });
  settingsChanges.on('allowUnverifiedCertificate', () => startPrinter());

  nativeTheme.on('updated', () => {
    if (settingsWindow && !settingsWindow.isDestroyed()) {
      settingsWindow.setTitleBarOverlay(titleBarOverlay());
    }
  });
  stopThemeWatch = watchTaskbarTheme(light => {
    lightTaskbar = light;
    trayManager?.setLightTaskbar(light);
  });

  startPrinter();
  if (isFirstTimeLaunch || status.connection === 'unconfigured' || status.connection === 'signed-out') { openSettingsWindow(); }
});

/**
 * Register/unregister the app to start at sign-in.
 * - Installed (Squirrel): start through Update.exe so the entry keeps working after updates.
 * - Development (`npm start`): never register. process.execPath is the bare electron.exe there, and starting it
 *   at sign-in just shows Electron's default welcome window.
 */
function applyRunAtStartup(enabled: boolean): void {
  if (process.platform !== 'win32') {
    app.setLoginItemSettings({ openAtLogin: enabled });
    return;
  }
  if (!app.isPackaged) {
    app.setLoginItemSettings({ openAtLogin: false });
    return;
  }
  const updateExe = path.resolve(path.dirname(process.execPath), '..', 'Update.exe');
  const args = ['--processStart', `"${path.basename(process.execPath)}"`];
  app.setLoginItemSettings({ openAtLogin: enabled, path: updateExe, args });
}

function quit() {
  stopThemeWatch?.();
  client?.stop();
  trayManager?.dispose();
  iconRenderer.dispose();
  app.quit();
}
